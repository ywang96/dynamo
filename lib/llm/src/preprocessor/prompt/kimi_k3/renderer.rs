/// Push ordinary (non-special) text. Empty text produces no segment, matching
/// python `_text`/`_segment` which return `[]` for `""`.
fn push_text(segs: &mut Vec<Segment>, text: &str) {
    if text.is_empty() {
        return;
    }
    segs.push(Segment {
        text: text.to_string(),
        allow_special: false,
    });
}

/// Push a structural marker (special). Always non-empty at call sites.
fn push_control(segs: &mut Vec<Segment>, text: &str) {
    if text.is_empty() {
        return;
    }
    segs.push(Segment {
        text: text.to_string(),
        allow_special: true,
    });
}

/// Escape an attribute value: `&` -> `&amp;` then `"` -> `&quot;` (order matters).
fn escape_attr(value: &str) -> String {
    value.replace('&', "&amp;").replace('"', "&quot;")
}

/// `_attr`: ` key`, `="`, escaped-value, `"` — four ordinary segments (value
/// segment omitted when empty, matching python `_text("")` -> `[]`).
fn push_attr(segs: &mut Vec<Segment>, key: &str, value: &str) {
    push_text(segs, &format!(" {key}"));
    push_text(segs, "=\"");
    push_text(segs, &escape_attr(value));
    push_text(segs, "\"");
}

/// `_open_tag`: OPEN(special) + tag + attrs + SEP(special).
fn open_tag(segs: &mut Vec<Segment>, tag: &str, attrs: &[(&str, String)]) {
    push_control(segs, OPEN);
    push_text(segs, tag);
    for (key, value) in attrs {
        push_attr(segs, key, value);
    }
    push_control(segs, SEP);
}

/// `_close_tag`: CLOSE(special) + tag + SEP(special).
fn close_tag(segs: &mut Vec<Segment>, tag: &str) {
    push_control(segs, CLOSE);
    push_text(segs, tag);
    push_control(segs, SEP);
}

fn end_of_msg(segs: &mut Vec<Segment>) {
    push_control(segs, END_OF_MSG);
}

/// `_append_text`: emit user/tool content text as ordinary tokens. Any literal
/// `<|kimi_image_placeholder|>` in string content is left inline verbatim — it
/// is not a special token, so it BPE-splits like any other text and the vLLM
/// backend later finds and expands it. Mirrors python `_append_text` with
/// `image_prompts=None` (no pre-substitution or splicing on the frontend side).
fn append_text(segs: &mut Vec<Segment>, text: &str) {
    push_text(segs, text);
}

