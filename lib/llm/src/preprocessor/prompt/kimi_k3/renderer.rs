//! Kimi-K3 XTML prompt segment builder.
//!
//! Byte-parity port of the K3 model's authoritative `encoding_k3.py`
//! `build_chat_segments` (via the reviewed smg implementation,
//! `Inferact/smg` `feat/k3-vllm-frontend`
//! `crates/tokenizer/src/encoders/kimi_k3.rs`). K3 ships no Jinja chat
//! template: prompts are a sequence of segments where structural XTML markers
//! (`<|open|>`, `<|close|>`, `<|sep|>`, `<|end_of_msg|>`, media placeholders)
//! are encoded as special tokens while user/tool text is encoded ordinarily,
//! so control-looking text cannot forge XTML structure.
//!
//! The committed goldens under `tests/data/kimi_k3/goldens/` are generated by
//! running `encoding_k3.py` itself (`gen_goldens.py`); this module is asserted
//! segment- and byte-identical against them.

use anyhow::{Result, anyhow};
use serde_json::{Map, Value};

// XTML structural markers — encoded as special tokens (allow_special = true).
const OPEN: &str = "<|open|>";
const CLOSE: &str = "<|close|>";
const SEP: &str = "<|sep|>";
const END_OF_MSG: &str = "<|end_of_msg|>";
/// Per-image placeholder emitted for image content parts (`config.json`
/// `image_placeholder`). The vLLM Kimi-K3 backend
/// (`KimiK3ForConditionalGeneration._get_prompt_updates`) searches the prompt
/// for this exact placeholder and expands each occurrence into the full
/// `<|media_begin|>image {w}x{h}<|media_content|>{pads}<|media_end|>` sequence,
/// so the frontend must emit the *unexpanded* placeholder — one per image —
/// exactly as the model's `encoding_k3.py` does with `image_prompts=None`.
///
/// Unlike `<|media_pad|>`, this is NOT a registered special token: it BPE-splits
/// into ordinary tokens on both the frontend (fastokens) and the backend
/// tokenizer, which is precisely what lets the backend's tokenizer-level match
/// find it. Emitting `<|media_pad|>` here instead (a real single special token
/// the backend never searches for) is what produced
/// `AssertionError: Failed to apply prompt replacement for mm_items['image'][0]`.
const KIMI_IMAGE_PLACEHOLDER: &str = "<|kimi_image_placeholder|>";

const VALID_THINKING_EFFORTS: [&str; 4] = ["low", "medium", "high", "max"];

/// One renderer output segment: text plus whether special-token patterns may
/// be recognized when encoding it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Segment {
    /// The literal text of this segment.
    pub text: String,
    /// `true` for renderer-owned structural markers (encoded as special
    /// tokens); `false` for user/tool-supplied text (encoded ordinarily).
    pub allow_special: bool,
}

/// Effective render controls, extracted from the request by the encoder
/// (`chat_template_args` + request-level `tool_choice`/`response_format`).
#[derive(Debug, Clone)]
pub struct RenderArgs {
    /// Thinking mode (default true): generation prompt opens the think channel.
    pub thinking: bool,
    /// Keep think channels for ALL assistant history messages.
    pub preserve_thinking: bool,
    /// `thinking_effort` control (`low`/`medium`/`high`/`max`; anything else
    /// is silently ignored, python parity).
    pub thinking_effort: Option<String>,
    /// Effective tool choice: only `"required"` / `"none"` emit control
    /// messages (python parity; `auto`/named emit nothing).
    pub tool_choice: Option<String>,
    /// OpenAI `response_format` value (`{"type": "json_object"}` /
    /// `{"type": "json_schema", "json_schema": {...}}`).
    pub response_format: Option<Value>,
    /// Whether to append the assistant generation prompt.
    pub add_generation_prompt: bool,
}

impl Default for RenderArgs {
    fn default() -> Self {
        Self {
            thinking: true,
            preserve_thinking: false,
            thinking_effort: None,
            tool_choice: None,
            response_format: None,
            add_generation_prompt: true,
        }
    }
}

// ---------------------------------------------------------------------------
// Python-default JSON writer (json.dumps(value, ensure_ascii=False))
// ---------------------------------------------------------------------------

mod json_dumps {
    //! Serialize a [`serde_json::Value`] like Python's
    //! `json.dumps(value, ensure_ascii=False)`: spaced `", "`/`": "`
    //! separators (default writer) or `","`/`":"` (compact writer), single
    //! line, raw UTF-8, and CPython `repr(float)` number notation. serde_json
    //! only ships compact and pretty formatters and formats floats via ryu
    //! (`1e-7`, `1e20`), while python emits `1e-07`, `1e+20`; XTML bodies must
    //! match the python bytes exactly.

    use std::io;

    use serde::Serialize;
    use serde_json::{
        Value,
        ser::{Formatter, Serializer},
    };

    /// Render `value` the way CPython's `repr(float)` / `json.dumps` does.
    ///
    /// ryu (serde_json's float writer) and CPython both print the shortest
    /// round-trip decimal, but their NOTATION differs: python uses scientific
    /// form iff the decimal exponent is `< -4` or `>= 16`, always writes the
    /// exponent sign, and zero-pads the exponent to two digits; integral
    /// positionals carry a trailing `.0`. This re-renders ryu's digits under
    /// python's rules.
    ///
    /// Known ingress-level divergence (documented, not fixable here):
    /// integers beyond i64/u64 range (e.g. 10^20) are parsed lossily into f64
    /// by serde_json at request ingress (`arbitrary_precision` is off
    /// workspace-wide), so python's `100000000000000000000` renders as
    /// `1e+20`. Floats themselves are exact.
    pub(super) fn python_float_repr(value: f64) -> String {
        if value == 0.0 {
            return if value.is_sign_negative() {
                "-0.0".to_string()
            } else {
                "0.0".to_string()
            };
        }
        // Shortest round-trip digits from serde_json's own (ryu) writer.
        let shortest = match serde_json::Number::from_f64(value) {
            Some(n) => n.to_string(),
            None => return "null".to_string(), // NaN/inf: unreachable via Value
        };
        let (sign, body) = match shortest.strip_prefix('-') {
            Some(rest) => ("-", rest),
            None => ("", shortest.as_str()),
        };
        // Parse `body` = digits[.digits][e[+|-]digits] into significant
        // digits + the exponent of the leading digit.
        let (mantissa, ryu_exp) = match body.split_once(['e', 'E']) {
            Some((m, e)) => (m, e.parse::<i32>().unwrap_or(0)),
            None => (body, 0),
        };
        let (int_part, frac_part) = match mantissa.split_once('.') {
            Some((i, f)) => (i, f),
            None => (mantissa, ""),
        };
        // Significant digits with leading zeros stripped; e10 = exponent of
        // the first significant digit (value = 0.d1d2... * 10^(e10+1)).
        let all: String = format!("{int_part}{frac_part}");
        let first_sig = all.find(|c: char| c != '0').unwrap_or(0);
        let digits = all[first_sig..].trim_end_matches('0').to_string();
        let digits = if digits.is_empty() {
            "0".to_string()
        } else {
            digits
        };
        let e10: i32 = int_part.len() as i32 - 1 - first_sig as i32 + ryu_exp;

        if (-4..16).contains(&e10) {
            // Positional notation.
            let d = digits.as_bytes();
            let n = d.len() as i32;
            let mut out = String::from(sign);
            if e10 < 0 {
                out.push_str("0.");
                for _ in 0..(-e10 - 1) {
                    out.push('0');
                }
                out.push_str(&digits);
            } else if n > e10 + 1 {
                out.push_str(&digits[..(e10 + 1) as usize]);
                out.push('.');
                out.push_str(&digits[(e10 + 1) as usize..]);
            } else {
                out.push_str(&digits);
                for _ in 0..(e10 + 1 - n) {
                    out.push('0');
                }
                out.push_str(".0");
            }
            out
        } else {
            // Scientific notation: d[.rest]e{+|-}NN (exponent >= 2 digits).
            let mut out = String::from(sign);
            out.push_str(&digits[..1]);
            if digits.len() > 1 {
                out.push('.');
                out.push_str(&digits[1..]);
            }
            out.push('e');
            if e10 < 0 {
                out.push('-');
            } else {
                out.push('+');
            }
            out.push_str(&format!("{:02}", e10.abs()));
            out
        }
    }

    struct PythonDefaultFormatter;

    impl Formatter for PythonDefaultFormatter {
        fn begin_object_value<W: ?Sized + io::Write>(&mut self, w: &mut W) -> io::Result<()> {
            w.write_all(b": ")
        }

        fn begin_object_key<W: ?Sized + io::Write>(
            &mut self,
            w: &mut W,
            first: bool,
        ) -> io::Result<()> {
            if first { Ok(()) } else { w.write_all(b", ") }
        }

        fn begin_array_value<W: ?Sized + io::Write>(
            &mut self,
            w: &mut W,
            first: bool,
        ) -> io::Result<()> {
            if first { Ok(()) } else { w.write_all(b", ") }
        }

        fn write_f64<W: ?Sized + io::Write>(&mut self, w: &mut W, value: f64) -> io::Result<()> {
            w.write_all(python_float_repr(value).as_bytes())
        }
    }

    /// Compact separators (serde default) but python float notation.
    struct PythonCompactFormatter;

    impl Formatter for PythonCompactFormatter {
        fn write_f64<W: ?Sized + io::Write>(&mut self, w: &mut W, value: f64) -> io::Result<()> {
            w.write_all(python_float_repr(value).as_bytes())
        }
    }

    fn serialize_with<F: Formatter>(value: &Value, formatter: F) -> String {
        let mut buf = Vec::new();
        let mut ser = Serializer::with_formatter(&mut buf, formatter);
        if value.serialize(&mut ser).is_err() {
            return "null".to_string();
        }
        String::from_utf8(buf).unwrap_or_else(|_| "null".to_string())
    }

    /// Serialize `value` like `json.dumps(value, ensure_ascii=False)`.
    pub(super) fn to_string(value: &Value) -> String {
        serialize_with(value, PythonDefaultFormatter)
    }

    /// Serialize `value` like
    /// `json.dumps(value, ensure_ascii=False, separators=(",", ":"))`.
    pub(super) fn to_string_compact(value: &Value) -> String {
        serialize_with(value, PythonCompactFormatter)
    }
}

