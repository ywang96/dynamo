/// `json.dumps(value, ensure_ascii=False, separators=(",", ":"))` — compact.
fn json_compact(value: &Value) -> String {
    json_dumps::to_string_compact(value)
}

/// `json.dumps(value, ensure_ascii=False)` — python default `", "`/`": "`.
fn json_default(value: &Value) -> String {
    json_dumps::to_string(value)
}

/// `deep_sort_dict`: recursively sort object keys. serde_json's
/// `preserve_order` feature is enabled transitively (via `dynamo-renderer`),
/// so insertion order is the serialized order and sorting must be explicit.
fn deep_sort(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let mut out = Map::new();
            for k in keys {
                out.insert(k.clone(), deep_sort(&map[k]));
            }
            Value::Object(out)
        }
        Value::Array(arr) => Value::Array(arr.iter().map(deep_sort).collect()),
        other => other.clone(),
    }
}

/// `_xtml_type`: bool -> boolean, null -> null, number -> number, string ->
/// string, object -> object, else array. (No "integer".)
fn xtml_type(value: &Value) -> &'static str {
    match value {
        Value::Bool(_) => "boolean",
        Value::Null => "null",
        Value::Number(_) => "number",
        Value::String(_) => "string",
        Value::Object(_) => "object",
        Value::Array(_) => "array",
    }
}

/// `_xtml_value`: strings raw, everything else `json.dumps(v, ensure_ascii=False)`.
fn xtml_value(value: &Value) -> String {
    match value {
        Value::String(s) => s.clone(),
        other => json_default(other),
    }
}

/// `extract_response_schema`: pull the JSON schema out of a response_format.
fn extract_response_schema(response_format: Option<&Value>) -> Option<Value> {
    let rf = response_format?;
    let json_schema = rf.get("json_schema")?;
    if json_schema.is_null() {
        return None;
    }
    if let Value::Object(js) = json_schema {
        if let Some(schema) = js.get("schema") {
            return Some(schema.clone());
        }
        if let Some(schema) = js.get("json_schema") {
            return Some(schema.clone());
        }
        return Some(json_schema.clone());
    }
    Some(json_schema.clone())
}

