/// `normalize_tool_arguments`: returns `(arguments_object, xtml_json_block)`.
/// - None/absent -> ({}, None)
/// - object -> (object, None)
/// - string: blank -> ({}, None); JSON object -> (object, None);
///   JSON non-object -> Err; unparseable -> ({}, Some(raw))
fn normalize_tool_arguments(arguments: Option<&Value>) -> Result<(Value, Option<String>)> {
    match arguments {
        None | Some(Value::Null) => Ok((Value::Object(Map::new()), None)),
        Some(Value::Object(m)) => Ok((Value::Object(m.clone()), None)),
        Some(Value::String(s)) => {
            if s.trim().is_empty() {
                return Ok((Value::Object(Map::new()), None));
            }
            match serde_json::from_str::<Value>(s) {
                Ok(Value::Object(m)) => Ok((Value::Object(m), None)),
                Ok(_) => Err(anyhow!(
                    "Kimi K3 tool call arguments must be a JSON object."
                )),
                Err(_) => Ok((Value::Object(Map::new()), Some(s.clone()))),
            }
        }
        Some(_) => Err(anyhow!(
            "Kimi K3 tool call arguments must be a dict or a JSON object string."
        )),
    }
}

/// `normalize_message`: deep-sort `tools`, and normalize each tool_call's
/// arguments (setting `_xtml_json_block` when the args string is unparseable).
fn normalize_message(message: &Value) -> Result<Value> {
    let Value::Object(obj) = message else {
        return Ok(message.clone());
    };
    let mut normalized = obj.clone();

    if let Some(tools) = normalized.get("tools")
        && !tools.is_null()
    {
        let sorted = deep_sort(tools);
        normalized.insert("tools".to_string(), sorted);
    }

    let tool_calls = normalized.get("tool_calls").cloned();
    let is_empty = match &tool_calls {
        None | Some(Value::Null) => true,
        Some(Value::Array(a)) => a.is_empty(),
        _ => false,
    };
    if is_empty {
        return Ok(Value::Object(normalized));
    }

    let mut normalized_calls = Vec::new();
    if let Some(Value::Array(calls)) = tool_calls {
        for tool_call in calls {
            let Value::Object(tc_map) = &tool_call else {
                normalized_calls.push(tool_call);
                continue;
            };
            let mut tc = tc_map.clone();
            if let Some(Value::Object(func)) = tc.get("function") {
                let mut fn_map = func.clone();
                let (args, json_block) = normalize_tool_arguments(fn_map.get("arguments"))?;
                fn_map.insert("arguments".to_string(), args);
                match json_block {
                    None => {
                        fn_map.remove("_xtml_json_block");
                    }
                    Some(b) => {
                        fn_map.insert("_xtml_json_block".to_string(), Value::String(b));
                    }
                }
                tc.insert("function".to_string(), Value::Object(fn_map));
            } else {
                let (args, json_block) = normalize_tool_arguments(tc.get("arguments"))?;
                tc.insert("arguments".to_string(), args);
                match json_block {
                    None => {
                        tc.remove("_xtml_json_block");
                    }
                    Some(b) => {
                        tc.insert("_xtml_json_block".to_string(), Value::String(b));
                    }
                }
            }
            normalized_calls.push(Value::Object(tc));
        }
    }
    normalized.insert("tool_calls".to_string(), Value::Array(normalized_calls));
    Ok(Value::Object(normalized))
}

/// `_tool_call_id_index`: map assistant `tool_calls[].id` ->
/// (1-based position, function name). Duplicate ids keep their first occurrence.
fn tool_call_id_index(tool_calls: Option<&Value>) -> Map<String, Value> {
    let mut index = Map::new();
    let Some(Value::Array(calls)) = tool_calls else {
        return index;
    };
    for (i, tool_call) in calls.iter().enumerate() {
        let Value::Object(tc) = tool_call else {
            continue;
        };
        let Some(call_id) = tc.get("id") else {
            continue;
        };
        if call_id.is_null() {
            continue;
        }
        let key = value_to_key(call_id);
        if index.contains_key(&key) {
            continue;
        }
        let name = match tc.get("function") {
            Some(Value::Object(f)) => f.get("name").cloned().unwrap_or(Value::Null),
            _ => tc.get("name").cloned().unwrap_or(Value::Null),
        };
        index.insert(key, Value::Array(vec![Value::from((i + 1) as u64), name]));
    }
    index
}

/// `str(call_id)` — stringify an id value for index keying/matching.
fn value_to_key(value: &Value) -> String {
    match value {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// `normalize_xtml_tool_result_messages`: re-sort consecutive tool-result runs
/// into assistant `tool_calls` order by `tool_call_id`, rewriting each matched
/// message's `tool`/`name` to the matched call's function name. Unresolved runs
/// are left untouched. Side-effect free.
fn normalize_tool_result_messages(messages: &[Value]) -> Vec<Value> {
    let mut output: Vec<Value> = Vec::with_capacity(messages.len());
    let mut current_index: Map<String, Value> = Map::new();
    let mut i = 0;
    let n = messages.len();

    while i < n {
        let message = &messages[i];
        let role = message.get("role").and_then(Value::as_str);

        if message.is_object() && role == Some("assistant") {
            current_index = tool_call_id_index(message.get("tool_calls"));
            output.push(message.clone());
            i += 1;
            continue;
        }

        if !message.is_object() || role != Some("tool") {
            output.push(message.clone());
            i += 1;
            continue;
        }

        // Gather a run of consecutive tool messages.
        // run item: (position, offset, message, name); position/name are
        // Option — None means unmatched.
        let mut run: Vec<(Option<u64>, usize, Value, Option<String>)> = Vec::new();
        let mut unresolved = false;
        let mut offset = 0;
        while i < n
            && messages[i].is_object()
            && messages[i].get("role").and_then(Value::as_str) == Some("tool")
        {
            let tool_message = &messages[i];
            let call_id = tool_message
                .get("tool_call_id")
                .or_else(|| tool_message.get("id"))
                .filter(|v| !v.is_null());
            let matched = call_id
                .map(value_to_key)
                .and_then(|k| current_index.get(&k).cloned());
            match matched {
                Some(Value::Array(pair)) if pair.len() == 2 => {
                    let position = pair[0].as_u64();
                    let name = pair[1].as_str().map(str::to_string);
                    run.push((position, offset, tool_message.clone(), name));
                }
                _ => {
                    unresolved = true;
                    run.push((None, offset, tool_message.clone(), None));
                }
            }
            offset += 1;
            i += 1;
        }

        if unresolved {
            for (_, _, msg, _) in run {
                output.push(msg);
            }
        } else {
            // Stable sort by (position, offset).
            run.sort_by_key(|a| (a.0, a.1));
            for (_, _, msg, name) in run {
                match name {
                    None => output.push(msg),
                    Some(name) => {
                        let mut resolved = msg;
                        if let Value::Object(m) = &mut resolved {
                            m.insert("tool".to_string(), Value::String(name.clone()));
                            if m.contains_key("name") {
                                m.insert("name".to_string(), Value::String(name));
                            }
                        }
                        output.push(resolved);
                    }
                }
            }
        }
    }
    output
}

