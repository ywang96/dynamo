/// `_render_content_segments`: string content or an array of OpenAI content
/// parts. Image parts emit one `<|kimi_image_placeholder|>` — the unexpanded
/// placeholder the vLLM Kimi-K3 backend searches for and expands per image.
fn render_content(segs: &mut Vec<Segment>, content: Option<&Value>) {
    match content {
        None | Some(Value::Null) => {}
        Some(Value::String(s)) => append_text(segs, s),
        Some(Value::Array(parts)) => {
            for part in parts {
                let kind = part.get("type").and_then(Value::as_str);
                if matches!(kind, Some("image") | Some("image_url")) {
                    push_control(segs, KIMI_IMAGE_PLACEHOLDER);
                } else if let Some(t) = part.get("text").and_then(Value::as_str) {
                    append_text(segs, t);
                }
            }
        }
        Some(other) => append_text(segs, &other.to_string()),
    }
}

/// `_internal_system_message`: a `role="system" type="..."` message whose body
/// is stripped.
fn internal_system_message(segs: &mut Vec<Segment>, message_type: &str, body: &str) {
    open_tag(
        segs,
        "message",
        &[
            ("role", "system".to_string()),
            ("type", message_type.to_string()),
        ],
    );
    push_text(segs, body.trim());
    close_tag(segs, "message");
    end_of_msg(segs);
}

/// `_render_tool_declare`: static or dynamic tool declaration system message.
/// The body is NOT stripped (unlike `_internal_system_message`).
fn render_tool_declare(segs: &mut Vec<Segment>, tools: &Value, dynamic: bool) {
    let json = json_compact(tools);
    let body = if dynamic {
        format!(
            "## New Tools Available\n\
             The system dynamically extends the toolset via lazy-loading.\n\
             You have access to all existing and extended tools.\n\
             Here are the specs for the extended tools.\n\n\
             ```json\n{json}\n```"
        )
    } else {
        format!(
            "# Tools\n\
             Here are the available tools, described in JSONSchema.\n\n\
             ```json\n{json}\n```"
        )
    };
    open_tag(
        segs,
        "message",
        &[
            ("role", "system".to_string()),
            ("type", "tool-declare".to_string()),
        ],
    );
    push_text(segs, &body);
    close_tag(segs, "message");
    end_of_msg(segs);
}

/// `_render_assistant_segments`: think (when kept + non-blank) + response +
/// tools channels, inside the already-opened assistant message.
fn render_assistant(segs: &mut Vec<Segment>, message: &Map<String, Value>, keep_think: bool) {
    let reasoning = message
        .get("reasoning_content")
        .filter(|v| !v.is_null())
        .or_else(|| message.get("reasoning").filter(|v| !v.is_null()));
    if keep_think && let Some(reasoning) = reasoning {
        let text = match reasoning {
            Value::String(s) => s.clone(),
            other => other.to_string(),
        };
        if !text.trim().is_empty() {
            open_tag(segs, "think", &[]);
            append_text(segs, &text);
            close_tag(segs, "think");
        }
    }

    open_tag(segs, "response", &[]);
    render_content(segs, message.get("content"));
    close_tag(segs, "response");

    let tool_calls = message.get("tool_calls");
    let has_calls = matches!(tool_calls, Some(Value::Array(a)) if !a.is_empty());
    if has_calls {
        open_tag(segs, "tools", &[]);
        if let Some(Value::Array(calls)) = tool_calls {
            for (i, tool_call) in calls.iter().enumerate() {
                let fn_obj = tool_call.get("function").unwrap_or(tool_call);
                let name = fn_obj
                    .get("name")
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                open_tag(
                    segs,
                    "call",
                    &[("tool", name.to_string()), ("index", (i + 1).to_string())],
                );
                let json_block = fn_obj.get("_xtml_json_block").and_then(Value::as_str);
                if let Some(block) = json_block {
                    open_tag(segs, "json", &[("type", "object".to_string())]);
                    append_text(segs, block);
                    close_tag(segs, "json");
                } else if let Some(Value::Object(args)) = fn_obj.get("arguments") {
                    for (key, value) in args {
                        open_tag(
                            segs,
                            "argument",
                            &[("key", key.clone()), ("type", xtml_type(value).to_string())],
                        );
                        append_text(segs, &xtml_value(value));
                        close_tag(segs, "argument");
                    }
                }
                close_tag(segs, "call");
            }
        }
        close_tag(segs, "tools");
    }
}

/// Build the K3 XTML prompt as a segment list — byte-parity with
/// `encoding_k3.py::build_chat_segments`.
///
/// `messages` is the OpenAI messages array; `tools` the request-level tool
/// list (deep-sorted before declaration).
pub fn build_chat_segments(
    messages: &Value,
    tools: Option<&Value>,
    args: &RenderArgs,
) -> Result<Vec<Segment>> {
    let Some(messages) = messages.as_array() else {
        return Err(anyhow!("Kimi K3 renderer expects a messages array"));
    };

    // 1. reorder tool-result runs; 2. normalize each message.
    let reordered = normalize_tool_result_messages(messages);
    let mut normalized: Vec<Value> = Vec::with_capacity(reordered.len());
    for m in &reordered {
        normalized.push(normalize_message(m)?);
    }

    // request-level tools, deep-sorted.
    let tools_sorted: Option<Value> = tools.filter(|t| !t.is_null()).map(deep_sort);

    // response schema (deep-sorted) derived from response_format.
    let response_format = args.response_format.as_ref().filter(|v| !v.is_null());
    let response_schema = extract_response_schema(response_format).map(|s| deep_sort(&s));

    let mut segs: Vec<Segment> = Vec::new();

    // last assistant WITHOUT tool_calls (-1 if none) -> keep-think boundary.
    let last_idx: isize = if args.preserve_thinking {
        -1
    } else {
        let mut found: isize = -1;
        for (i, m) in normalized.iter().enumerate().rev() {
            let is_plain_assistant = m.get("role").and_then(Value::as_str) == Some("assistant")
                && !matches!(m.get("tool_calls"), Some(Value::Array(a)) if !a.is_empty());
            if is_plain_assistant {
                found = i as isize;
                break;
            }
        }
        found
    };

    // running assistant tool_calls / tool-result index for name resolution.
    let mut tool_calls: Option<Value> = None;
    let mut tool_index: usize = 0;

    if let Some(tools) = &tools_sorted
        && matches!(tools, Value::Array(a) if !a.is_empty())
    {
        render_tool_declare(&mut segs, tools, false);
    }

    if args.thinking
        && let Some(effort) = args.thinking_effort.as_deref()
        && VALID_THINKING_EFFORTS.contains(&effort)
    {
        internal_system_message(
            &mut segs,
            "thinking-effort",
            &format!(
                "`thinking_effort` guides on how much to think in your \
                 thinking channel (not including the response channel), \
                 supported values include `low`, `medium`, `high`, and `max`.\n\
                 Now the system is invoked with `thinking_effort={effort}`."
            ),
        );
    }

    for (message_index, message) in normalized.iter().enumerate() {
        let Value::Object(obj) = message else {
            continue;
        };
        let role = obj.get("role").and_then(Value::as_str).unwrap_or_default();

        match role {
            "user" => {
                let mut attrs = vec![("role", "user".to_string())];
                if let Some(name) = obj.get("name").and_then(Value::as_str)
                    && !name.is_empty()
                {
                    attrs.push(("name", name.to_string()));
                }
                open_tag(&mut segs, "message", &attrs);
                render_content(&mut segs, obj.get("content"));
                close_tag(&mut segs, "message");
                end_of_msg(&mut segs);
            }
            "system" => {
                if let Some(tools) = obj.get("tools").filter(|t| !t.is_null()) {
                    // Already deep-sorted by normalize_message; render a
                    // dynamic declare. System content is intentionally NOT
                    // rendered (python semantics).
                    render_tool_declare(&mut segs, tools, true);
                } else {
                    let mut attrs = vec![("role", "system".to_string())];
                    if let Some(name) = obj.get("name").and_then(Value::as_str)
                        && !name.is_empty()
                    {
                        attrs.push(("name", name.to_string()));
                    }
                    open_tag(&mut segs, "message", &attrs);
                    render_content(&mut segs, obj.get("content"));
                    close_tag(&mut segs, "message");
                    end_of_msg(&mut segs);
                }
            }
            "tool" => {
                tool_index += 1;
                let mut tool_name: Option<String> = if let Some(t) = obj.get("tool") {
                    t.as_str().map(str::to_string)
                } else {
                    obj.get("name").and_then(Value::as_str).map(str::to_string)
                };
                if tool_name.is_none()
                    && let Some(Value::Array(calls)) = &tool_calls
                    && tool_index <= calls.len()
                {
                    let tc = &calls[tool_index - 1];
                    let fn_obj = tc.get("function").unwrap_or(tc);
                    tool_name = fn_obj
                        .get("name")
                        .and_then(Value::as_str)
                        .map(str::to_string);
                }
                let Some(tool_name) = tool_name else {
                    return Err(anyhow!(
                        "Kimi K3 tool messages need a resolvable tool name: carry \
                         `tool`/`name`, or match a preceding assistant tool_call by order."
                    ));
                };
                open_tag(
                    &mut segs,
                    "message",
                    &[
                        ("role", "tool".to_string()),
                        ("tool", tool_name),
                        ("index", tool_index.to_string()),
                    ],
                );
                render_content(&mut segs, obj.get("content"));
                close_tag(&mut segs, "message");
                end_of_msg(&mut segs);
            }
            "assistant" => {
                tool_calls = obj.get("tool_calls").cloned();
                tool_index = 0;
                let mut attrs = vec![("role", "assistant".to_string())];
                if let Some(name) = obj.get("name").and_then(Value::as_str)
                    && !name.is_empty()
                {
                    attrs.push(("name", name.to_string()));
                }
                open_tag(&mut segs, "message", &attrs);
                let keep_think = args.preserve_thinking || (message_index as isize) > last_idx;
                render_assistant(&mut segs, obj, keep_think);
                close_tag(&mut segs, "message");
                end_of_msg(&mut segs);
            }
            _ => {}
        }
    }

    // tool_choice control message (emitted purely on the effective value).
    match args.tool_choice.as_deref() {
        Some("required") => internal_system_message(
            &mut segs,
            "tool-choice",
            "The system is invoked with `tool_choice=required`.\n\
             You MUST call tools in the next message.",
        ),
        Some("none") => internal_system_message(
            &mut segs,
            "tool-choice",
            "The system is invoked with `tool_choice=none`.\n\
             You MUST NOT call any tools in the next message.",
        ),
        _ => {}
    }

    // response_format control message.
    let rf_type = response_format.and_then(|rf| {
        if rf.is_object() {
            rf.get("type").and_then(Value::as_str)
        } else {
            rf.as_str()
        }
    });
    match rf_type {
        Some("json_object") => internal_system_message(
            &mut segs,
            "response-format",
            "The system is invoked with `response_format=json_object`.\n\
             Your response must be raw JSON data without markdown code blocks \
             (```json) or any additional formatting.",
        ),
        Some("json_schema") => {
            let schema = response_schema
                .as_ref()
                .map(json_compact)
                .unwrap_or_default();
            internal_system_message(
                &mut segs,
                "response-format",
                &format!(
                    "The system is invoked with `response_format=json_schema`.\n\
                     Your response must be raw JSON data without markdown code blocks \
                     (```json) or any additional formatting.\n\
                     The JSON data must match the following schema:\n\
                     ```json\n{schema}\n```"
                ),
            );
        }
        _ => {}
    }

    if args.add_generation_prompt {
        open_tag(&mut segs, "message", &[("role", "assistant".to_string())]);
        open_tag(
            &mut segs,
            if args.thinking { "think" } else { "response" },
            &[],
        );
    }

    Ok(segs)
}

